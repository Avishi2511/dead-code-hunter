"""Markdown report and ``git am``-compatible patch for a combined cleanup."""

from __future__ import annotations

from collections import defaultdict
from datetime import UTC, datetime
from email.utils import format_datetime

from dch.cleanup.apply import Applied
from dch.result import CleanupSummary, Finding, Selection, ValidationReport

TYPE_TITLES = {
    "unused_function": "Unused functions",
    "unused_class": "Unused classes",
    "unused_method": "Unused methods",
    "unused_variable": "Unused variables",
    "unused_import": "Unused imports",
    "unused_module": "Unused modules",
    "unused_dependency": "Unused dependencies",
    "unused_route": "Unused routes",
    "unreachable_code": "Unreachable code",
}
STATUS_MARK = {"pass": "passed", "fail": "FAILED", "skipped": "skipped"}


def commit_message(summary: CleanupSummary) -> str:
    parts = ", ".join(f"{n} {TYPE_TITLES[t].lower()}" for t, n in sorted(summary.by_type.items()))
    return (
        f"Remove dead code found by Dead Code Hunter\n\n"
        f"{summary.findings} findings applied ({parts}); {summary.files_changed} files changed, "
        f"{summary.lines_removed} lines removed, {summary.lines_added} added.\n"
        "Findings come from static analysis; review before merging."
    )


def build_patch(diff: str, summary: CleanupSummary, base_sha: str | None) -> str:
    message = commit_message(summary)
    subject, _, body = message.partition("\n\n")
    stamp = format_datetime(datetime.now(UTC))
    header = (
        f"From {base_sha or '0' * 40} Mon Sep 17 00:00:00 2001\n"
        "From: Dead Code Hunter <dead-code-hunter@users.noreply.github.com>\n"
        f"Date: {stamp}\nSubject: [PATCH] {subject}\n\n{body}\n---\n"
    )
    return f"{header}{diff}-- \ndch\n"


def finding_lines(finding: Finding) -> list[str]:
    lines = [
        f"- `{finding.name}` — `{finding.file}:{finding.line}` — {finding.confidence}% ({finding.level})"
    ]
    for item in finding.evidence:
        mark = "✓" if item.polarity == "supports" else "⚠"
        lines.append(f"  - {mark} {item.text}")
    return lines


def build_report(
    findings: dict[str, Finding], selections: list[Selection], applied: Applied, summary: CleanupSummary,
    validation: ValidationReport, base_sha: str | None,
) -> str:  # fmt: skip
    actions = {s.finding_id: s.action for s in selections}
    removed: dict[str, list[Finding]] = defaultdict(list)
    alive: list[Finding] = []
    for fid in applied.applied:
        finding = findings.get(fid)
        if finding is None:
            continue
        (alive if actions.get(fid) == "mark_alive" else removed[finding.type]).append(finding)

    out = ["# Dead Code Cleanup Report", ""]
    out.append(f"Generated by Dead Code Hunter · base commit `{base_sha or 'unknown'}`")
    out += [
        "",
        "> Findings come from static analysis. They are strong signals, not proof — review before merging.",
        "",
    ]
    out += ["## Summary", ""]
    out.append(f"- Findings applied: **{summary.findings}** · files changed: **{summary.files_changed}**")
    out.append(f"- Lines removed: **{summary.lines_removed}** · lines added: **{summary.lines_added}**")
    out.append(f"- Marked as alive: **{len(alive)}**")
    out.append("")
    for type_, items in removed.items():
        out += [f"## {TYPE_TITLES[type_]} ({len(items)})", ""]
        for finding in items:
            out += finding_lines(finding)
        out.append("")
    if applied.cascades:
        out += ["## Also removed", ""] + [f"- {c}" for c in applied.cascades] + [""]
    if alive:
        out += [
            "## Marked as alive",
            "",
            "Recorded in `.deadcodehunter.toml` so they are not reported again.",
            "",
        ]
        for finding in alive:
            out += finding_lines(finding)
        out.append("")
    if applied.covered or applied.manual:
        out += ["## Not applied", ""]
        out += [
            f"- `{fid}` is covered by `{owner}` and was skipped" for fid, owner in applied.covered.items()
        ]
        out += [f"- `{fid}` needs manual cleanup: {why}" for fid, why in applied.manual.items()]
        out.append("")
    out += ["## Files changed", ""] + [f"- `{path}`" for path in applied.changed] + [""]
    out += ["## Validation", "", "Static checks only; the project's own test suite was **not** run.", ""]
    out.append(f"- `compileall`: {STATUS_MARK[validation.compileall]}")
    out.append(f"- `ruff` (F401, F811, F821) new issues vs baseline: {STATUS_MARK[validation.ruff]}")
    out += [f"  - {issue}" for issue in validation.ruff_new_issues]
    out.append(f"- Type check (basedpyright) new errors vs baseline: {STATUS_MARK[validation.typecheck]}")
    out += [f"  - {issue}" for issue in validation.typecheck_new_errors]
    out += [f"- note: {note}" for note in validation.notes]
    out += ["", "## Apply", "", "```bash", "git apply dead-code-cleanup.patch", "```", ""]
    return "\n".join(out)
